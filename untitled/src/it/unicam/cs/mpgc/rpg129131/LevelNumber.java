package it.unicam.cs.mpgc.rpg129131;

/**
 * Identifica i tre livelli previsti dal gioco.
 *
 * I valori dell'enumerazione sono distinti dagli indici delle liste:
 * ONE rappresenta il primo livello, che nella lista ha indice zero.
 */
public enum LevelNumber {

    /**
     * Primo livello del gioco.
     */
    ONE,

    /**
     * Secondo livello del gioco.
     */
    TWO,

    /**
     * Terzo e ultimo livello del gioco.
     */
    THREE
}